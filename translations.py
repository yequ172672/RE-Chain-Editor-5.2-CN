def _build_language_table():
    """Build independent language dictionaries for Blender's registry."""
    table = {}
    for language in LANGUAGES:
        # Blender does not fall back from an explicit ``Operator`` context to
        # ``*``.  Register interface/operator labels in both contexts so the
        # same source string remains translated when Blender asks for it from
        # a file menu, operator button, tooltip, or RNA panel.
        entries = {("*", source): target for source, target in interface_translations.items()}
        entries.update({("Operator", source): target for source, target in interface_translations.items()})
        entries.update({("*", source): target for source, target in operator_translations.items()})
        entries.update({("Operator", source): target for source, target in operator_translations.items()})
        table[language] = entries
    return table


translations_dict = _build_language_table()


def register():
    """Register translations for this add-on only."""
    bpy.app.translations.register(__name__, translations_dict)


def unregister():
    """Unregister translations without touching Blender preferences."""
    bpy.app.translations.unregister(__name__)


def interface(message, *args, context="*", **kwargs):
    """Translate a dynamic interface string, preserving English as fallback."""
    translated = pgettext_iface(message, context)
    return translated.format(*args, **kwargs) if (args or kwargs) else translated


def tip(message, *args, context="Operator", **kwargs):
    """Translate a dynamic operator tooltip/popup string."""
    translated = pgettext_tip(message, context)
    return translated.format(*args, **kwargs) if (args or kwargs) else translated


def report(message, *args, **kwargs):
    """Translate an operator report using Blender's ``Operator`` context."""
    return tip(message, *args, context="Operator", **kwargs)


